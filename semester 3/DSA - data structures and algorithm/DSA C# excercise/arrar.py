# Array-based implementation using Python's list

# Initialize an empty list
array = []

# Insertion: Append elements to the array
array.append(10)
array.append(20)
array.append(30)

# Deletion: Remove an element from the array by value
array.remove(20)

# Traversal: Iterate through the array and print each element
for element in array:
    print(element)
